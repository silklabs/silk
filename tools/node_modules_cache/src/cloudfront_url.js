/**
 * Creates the cloud front url...
 *
 * @flow
 */

import path from 'path';
import cloudfront from 'aws-cloudfront-sign';

const KEY_PAIR_ID = 'APKAITLLREMOUE2AB6AQ';
const DOMAIN = 'https://d1jb8xvh2gmalu.cloudfront.net';
const PRIVATE_KEY_PATH = path.join(__dirname, '../cloudfront.pem');

/**
 * Takes an S3 object key and returns a signed cloudfront url.
 */
export default function (key: string, expires?: Date): string {
  // Default to a shorter expire time we may not want these to live forever
  // generally...
  if (!expires) {
    expires = new Date();
    expires.setMinutes(expires.getMinutes() + 15);
  }

  let url = `${DOMAIN}/${key}`;
  return cloudfront.getSignedUrl(url, {
    expireTime: expires,
    keypairId: KEY_PAIR_ID,
    privateKeyPath: PRIVATE_KEY_PATH
  });
}
