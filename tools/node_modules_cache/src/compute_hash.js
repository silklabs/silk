/**
 * This module computes a hash for a given package.json can be used to identify
 * and store content remotely.
 *
 * @flow
 */

import invariant from 'assert';
import crypto from 'crypto';
import stableStringify from 'json-stable-stringify';
import createLog from 'debug';
import {DEPENDENCY_KEYS} from './package';

import type {PackageJSON} from './package';

const log = createLog('compute-hash');

export default function (packageJSON: PackageJSON): string {
  /**
   * The goal of the hash is to detect changes to dependencies but we don't want
   * to pick up other stuff... The exception being "name" which we use to isolate
   * the various packages.
   */
  invariant(packageJSON.name, 'given package must have .name');
  let hashable: PackageJSON = { name: packageJSON.name };

  for (let section of DEPENDENCY_KEYS) {
    if (section in packageJSON) {
      hashable[section] = packageJSON[section];
    }
  }

  let hashInput = stableStringify(hashable);
  log('computing hash on', hashInput);
  let result = crypto.createHash('sha256').update(hashInput);
  invariant(result);
  return result.digest('hex');
}
