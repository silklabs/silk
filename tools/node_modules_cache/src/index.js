/**
 * Main for this module intended to be used as/in CLI.
 *
 * @flow
 */
import computeHash from './compute_hash';
import s3, {BUCKET} from './s3';
import {S3} from 'aws-sdk-promise';
import run from './run';
import bundle, {METADATA_PATH} from './bundle';
import install from './install';
import cloudfrontUrl from './cloudfront_url';
import createDebug from 'debug';
import path from 'path';
import tmp from './tmp';
import fs from 'fs';
import {createGzip as gzip} from 'zlib';
import {spawn} from 'child_process';

const debug = createDebug('node_modules_cache');

async function upload(modulePkg, directory, objectKey){
  debug('Doing upload for', directory);
  let stream = await bundle(modulePkg, directory);
  let options = { Key: objectKey, Bucket: BUCKET, Body: stream };
  let managed = new S3.ManagedUpload({ params: options });

  await new Promise((accept, reject) => {
    managed.send((err) => {
      if (err) {
        reject(err);
        return;
      }
      accept();
    });
  });
}

async function download(modulePkg, directory, objectKey) {
  let url = cloudfrontUrl(objectKey);
  let metadataPath = path.join(directory, METADATA_PATH);
  let nodeModules = path.join(directory, 'node_modules');
  if (!fs.existsSync(nodeModules)) {
    fs.mkdirSync(nodeModules);
  }

  if (fs.existsSync(metadataPath)) {
    let metadata = require(metadataPath);
    debug('Has metadata', metadata);
    if (metadata.hash === objectKey) {
      console.log(`Hash matches previous install will not force reinstall.`)
      console.log(`Please remove node_modules if you want full reinstall from cache.`);
      return;
    }
  }

  let tmpHome = tmp();
  let tmpNodeModules = path.join(tmpHome, 'node_modules');

  await run(`curl -L '${url}' | tar -xz`, { cwd: tmpHome });
  await install(tmpHome);

  let installedModules = fs.readdirSync(tmpNodeModules);
  if (installedModules.length) {
    await run(`rm -rf ${installedModules.join(' ')}`, {
      cwd: nodeModules
    });

    await run(`mv ${installedModules.join(' ')} '${nodeModules}'`, {
      cwd: tmpNodeModules
    });
  }
}

async function main(
  action = process.argv[2],
  modulePath = process.argv[3],
) {
  modulePath = path.resolve(modulePath || process.cwd());
  action = action || 'download';
  let modulePkg = require(`${modulePath}/package.json`);

  let hash = computeHash(modulePkg);
  debug(`Checking ${modulePath} with hash ${hash}`);

  let exists = false;
  try {
    await s3.headObject({
      Bucket: BUCKET,
      Key: hash
    }).promise();
    exists = true;
  } catch (err) {
    if (err.statusCode !== 404) {
      console.error('Failed during HEAD with unexpected error', err.stack)
      process.exit(1);
    }
  }

  switch (action) {
  case 'upload':
    if (!exists) {
      await upload(modulePkg, modulePath, hash);
      return;
    }
    console.log(`${modulePath} already has cache.`);
    break;
  case 'download':
    if (exists) {
      await download(modulePkg, modulePath, hash);
      return;
    }
    console.warn(`No cached dependencies for: ${modulePath}`);
    break;
  default:
    console.error('Available actions are: upload | download');
    process.exit(1);
  }
}

export default main;

if (process.mainModule === module) {
  main().catch((err) => {
    setTimeout(() => {
      throw err;
    });
  });
}
