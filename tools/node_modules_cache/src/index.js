const AWS_SECRET_ACCESS_KEY = 'X8Tl+9tiDBaoNGL+kIOWjTi6H4nPALlOlMzTmYZi';
const REGION = 'us-west-2';

// XXX: For whatever reason passing the credentials explicitly does not work so
// provide them as enviornment env.
Object.assign(process.env, { AWS_ACCESS_KEY, AWS_SECRET_ACCESS_KEY });

let s3 = new S3({
  region: REGION
});

function upload(modulePkg, directory, objectKey){
  log.info('Doing upload for', directory);
  let stream = bundle(modulePkg, directory).pipe(gzip());
  let options = { Key: objectKey, Bucket: BUCKET, Body: stream };
  let managed = new S3.ManagedUpload({ params: options });

  managed.send((err) => {
    if (err) {
      console.error(`Error uploading ${directory} node_modules cache`);
      console.error(err.stack);
      process.exit(1);
      return;
    }
  });
}

async function download(modulePkg, directory, objectKey) {
  let url = s3.getSignedUrl('getObject', {
    Bucket: BUCKET,
    Key: objectKey
  });

  let cmd = `curl -L '${url}' | tar -xz`;
  let proc = spawn(
    '/bin/bash',
    ['-c', cmd],
    { cwd: directory, stdio: 'inherit' }
  );

  proc.on('exit', (code) => {
    if (code !== 0) process.exit(code);
  });
}

async function main(
  action = process.argv[2],
  modulePath = process.argv[3],
) {
  modulePath = path.resolve(modulePath || process.cwd());
  action = action || 'download';

  let modulePkg = require(`${modulePath}/package.json`);

  let hash = computeHash(modulePkg);
  log.info(`Checking ${modulePath} with hash ${hash}`);

  let exists = false;
  try {
    await s3.headObject({
      Bucket: BUCKET,
      Key: hash
    }).promise();
    exists = true;
  } catch (err) {
    if (err.statusCode !== 404) {
      throw err;
    }
  }

  switch (action) {
  case 'upload':
    if (!exists) {
      return upload(modulePkg, modulePath, hash);
    }
    console.log(`${modulePath} already has cache.`);
    break;
  case 'download':
    if (exists) {
      return download(modulePkg, modulePath, hash);
    }
    console.warn(`No cached dependencies for: ${modulePath}`);
    break;
  default:
    console.error('Available actions are: upload | download');
    process.exit(1);
  }

}

main().catch((err) => {
  setTimeout(() => {
    throw err;
  });
});
