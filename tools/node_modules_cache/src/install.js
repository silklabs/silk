/**
 * Complete an "install" of a prebundled node_modules that has been expanded.
 *
 * @flow
 */

import run from './run';

export default async function (modulePath: string): Promise<void> {
  // XXX: A hack to allow rebuilds to fail in specific instances (such as during
  // the android build system installs...).
  let isFatal = true;
  if (process.env.SILK_ALLOW_REBUILD_FAIL === '1') {
    isFatal = false;
  }

  try {
    await run(`npm rebuild`, { cwd: modulePath });
  } catch (err) {
    if (isFatal) {
      throw err;
    }
    console.warn(`Failed to rebuild: ${modulePath} (non fatal).`);
  }
}
