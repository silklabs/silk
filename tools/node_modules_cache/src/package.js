/**
 * misc package.json related utilities.
 *
 * @flow
 */

import invariant from 'assert';

export type PackageJSON = {
  name?: string;
  dependencies?: Object;
  devDependencies?: Object;
  bundledDependencies?: Object;
  optionalDependencies?: Object;
  peerDependencies?: Object;
}

export const DEPENDENCY_KEYS = [
  'dependencies',
  'devDependencies',
  'bundledDependencies',
  'optionalDependencies',
  'peerDependencies'
];

export function dependencies(pkg: PackageJSON): Array<string> {
  let result = new Set([]);
  for (let key of DEPENDENCY_KEYS) {
    if (key in pkg) {
      invariant(pkg[key]);
      let names = Object.keys(pkg[key]);
      for (let name of names) result.add(name);
    }
  }

  return Array.from(result);
}
