/**
 * Run a process via spawn sharing stderr/stdout with the node process.
 *
 * @flow
 */

import {spawn} from 'child_process';
import eventToPromise from 'event-to-promise';

type Options = {
  cwd?: string;
  env?: Object;
};

export default async function (cmd: string, options: Options = {}) {
  options = Object.assign({}, options, { stdio: 'inherit' });
  console.time(cmd);
  let proc = spawn('/bin/bash', ['-c', cmd], options);
  let code = await eventToPromise(proc, 'exit');
  console.timeEnd(cmd);
  if (code !== 0) {
    throw new Error(`Failed to run: ${cmd}`);
  }
}
