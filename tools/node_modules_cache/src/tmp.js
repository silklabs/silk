/**
 * Find and create temp directory.
 *
 * @flow
 */

import os from 'os';
import path from 'path';
import fs from 'fs';
import {execSync} from 'child_process';

// One prefix per process that may be running... This does not strictly need to
// be unique. NOTE: You cannot use "node_modules" as part of the path name as it
// will result in weird errors in how lifecycle hooks are run (path will be
// incorrectly computed).
const PREFIX = `.silk_npmcache-${process.pid}`;
const ROOT = path.join(__dirname, '../../', PREFIX);
let currentId = 1;
fs.mkdirSync(ROOT);

process.on('exit', () => {
  execSync(`rm -rf ${ROOT}`);
});

export default function() {
  // This code is run synchronously blocked on single thread so should be fine
  // to use simple incremental counter.
  let tmpPath = path.join(ROOT, String(currentId++));
  fs.mkdirSync(tmpPath);
  return tmpPath;
}
