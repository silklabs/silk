import assert from 'assert';
import compute from '../src/compute_hash';

suite('compute hash', function() {

  test('generate hash in various states', async () => {
    // empty package to start...
    let pkg = { name: 'silk-test' };
    let hash = compute(pkg);

    // Add unrelated data...
    pkg.main = 'index.js';
    assert.equal(hash, compute(pkg));

    // Add dependency
    pkg.dependencies = { 'foo': '1.0' };
    assert.notEqual(hash, compute(pkg));
    hash = compute(pkg);

    // Add devDependency
    pkg.devDependencies = { 'bar': '1.0', 'buzz': '1.0' };
    assert.notEqual(hash, compute(pkg));

    // Verify determinisitic (yes js does order these...)
    let duplicate = {};
    duplicate.dependencies = pkg.dependencies;
    duplicate.devDependencies = pkg.devDependencies;
    duplicate.name = pkg.name;

    assert.equal(compute(pkg), compute(duplicate));
  });

});
