import assert from 'assert';
import * as pkg from '../src/package';

suite('package', function() {

  suite('dependencies', function() {

    [
      {
        expected: ['a', 'b', 'c'],
        input: {
          devDependencies: { 'c': 1 },
          dependencies: { 'a': 1 },
          peerDependencies: { 'c': 1 },
          optionalDependencies: { 'b': 1 },
        }
      },
      {
        expected: [],
        input: {}
      }
    ].forEach((fixture) => {
      let {expected, input} = fixture;
      test(`validate: ${JSON.stringify(input)}`, async () => {
        let actual = pkg.dependencies(input);
        assert.deepEqual(actual.sort(), expected.sort());
      });
    });

  });

});
